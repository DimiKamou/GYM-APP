/**
 * The service worker: what lets the installed app open with no signal.
 *
 * It was held back until M5 because, during a live pilot, a worker serves the trainer the bug
 * fixed an hour ago. The Play Store build changes the trade: an installed app that shows
 * Chrome's offline page on a cold start is an app with a one-star review, and the athlete
 * reading their sheet on the bus has no wifi to wait for. So it ships — with the two rules
 * that keep the original objection answered:
 *
 *  1. **A new build never takes over by itself.** The waiting worker is announced
 *     (`useUpdateReady`) and applied by a tap, so a coach is never reloaded mid-set.
 *  2. **It looks for a new build every time the app comes back to the foreground** and every
 *     half hour, so "fixed at 09:15, live for the 09:30 client" still holds for anyone who
 *     taps the banner.
 *
 * Registered by hand rather than through `virtual:pwa-register`: the single-file preview build
 * has no PWA plugin and must still compile, and a 404 on `/sw.js` there is simply no worker.
 * The worker itself is generated by vite-plugin-pwa (see vite.config.ts) and precaches the
 * build; it never caches Supabase — that is the persisted query cache's job, with its own ages.
 */

import { useSyncExternalStore } from 'react'

type Apply = () => void

let pending: Apply | null = null
const listeners = new Set<() => void>()

function announce(apply: Apply | null): void {
  pending = apply
  for (const listener of listeners) listener()
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

/** The function that switches to the waiting build, or null while there is none. */
export function useUpdateReady(): Apply | null {
  return useSyncExternalStore(subscribe, () => pending, () => null)
}

const UPDATE_INTERVAL_MS = 30 * 60_000

export function registerServiceWorker(): void {
  if (import.meta.env.DEV || typeof window === 'undefined' || !('serviceWorker' in navigator)) return

  const offer = (worker: ServiceWorker) =>
    announce(() => {
      // generateSW's worker listens for exactly this message and only then skips waiting.
      worker.postMessage({ type: 'SKIP_WAITING' })
    })

  window.addEventListener('load', () => {
    navigator.serviceWorker
      .register('/sw.js', { scope: '/' })
      .then((registration) => {
        // A build that finished installing while the app was closed.
        if (registration.waiting && navigator.serviceWorker.controller) offer(registration.waiting)

        registration.addEventListener('updatefound', () => {
          const installing = registration.installing
          installing?.addEventListener('statechange', () => {
            // With no controller this is the first install, not an update: nothing to offer.
            if (installing.state === 'installed' && navigator.serviceWorker.controller) offer(installing)
          })
        })

        const check = () => void registration.update().catch(() => undefined)
        window.setInterval(check, UPDATE_INTERVAL_MS)
        document.addEventListener('visibilitychange', () => {
          if (document.visibilityState === 'visible') check()
        })
      })
      .catch(() => {
        // No worker: the preview build, a file:// open, a browser that refuses. The app works
        // exactly as it did before there was one.
      })

    // The tapped update has taken control: load the build it serves. Once.
    let reloading = false
    navigator.serviceWorker.addEventListener('controllerchange', () => {
      if (reloading) return
      reloading = true
      window.location.reload()
    })
  })
}
